import { SEVERITY_EMOJI } from "@codelens/types";

export interface RenderFinding {
  severity: string;
  category: string;
  file: string;
  line: number | null;
  title: string;
  description: string;
  recommendation?: string | null;
  confidence: number;
  source: string;
}

/**
 * Inline PR comment body. Compact, actionable, confidence-transparent.
 */
export function renderInlineComment(f: RenderFinding): string {
  const icon = SEVERITY_EMOJI[f.severity] ?? "⚪";
  const lines: string[] = [];
  lines.push(`**CodeLens** ${icon} \`${f.severity}\` — ${f.title}`);
  lines.push("");
  lines.push(f.description);
  if (f.recommendation) {
    lines.push("");
    lines.push(`**Suggestion:** ${f.recommendation}`);
  }
  lines.push("");
  lines.push(`<sub>category: ${f.category.toLowerCase()} | source: ${f.source === "AI" ? "AI (validated)" : "static analysis"} | confidence: ${Math.round(f.confidence * 100)}%</sub>`);
  return lines.join("\n");
}

export interface SummaryInput {
  prTitle: string;
  filesAnalyzed: number;
  linesChanged: number;
  severityCounts: Record<string, number>;
  qualityScore: number;
  mainAreas: string[];
  aiSummary?: string | null;
}

/**
 * PR-level summary comment.
 */
export function renderSummaryComment(input: SummaryInput): string {
  const s = input.severityCounts;
  const parts: string[] = [];
  parts.push("## CodeLens Review");
  parts.push("");
  parts.push(`**Files analyzed:** ${input.filesAnalyzed} | **Lines changed:** ${input.linesChanged}`);
  parts.push("");
  parts.push("### Findings");
  parts.push(`- ${SEVERITY_EMOJI.CRITICAL} Critical: ${s.CRITICAL}`);
  parts.push(`- ${SEVERITY_EMOJI.HIGH} High: ${s.HIGH}`);
  parts.push(`- ${SEVERITY_EMOJI.MEDIUM} Medium: ${s.MEDIUM}`);
  parts.push(`- ${SEVERITY_EMOJI.LOW} Low: ${s.LOW}`);
  parts.push("");
  parts.push(`**Code quality:** ${input.qualityScore}/100 _(transparent heuristic — see findings for substance)_`);
  if (input.mainAreas.length > 0) {
    parts.push("");
    parts.push(`**Main areas:** ${input.mainAreas.map((a) => `${a}`).join(" • ")}`);
  }
  if (input.aiSummary) {
    parts.push("");
    parts.push("### AI Summary");
    parts.push(input.aiSummary);
  }
  parts.push("");
  parts.push("<sub>Generated by CodeLens. AI findings are validated against the diff and can be marked as false positives in the dashboard.</sub>");
  return parts.join("\n");
}
